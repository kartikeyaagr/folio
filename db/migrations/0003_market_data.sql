-- What the exchange tells us: prices, filings, financials, insider dealing, shareholding.
--
-- Everything here is written by ingest and read by everything else. No person types into these
-- tables, which is why every one of them carries the source it came from: when a figure looks
-- wrong the first question is always "wrong where", and the answer has to be in the row.

-- The security master needs to say which platform a symbol lists on. SEBI's filing deadlines
-- differ — an SME on NSE Emerge files half-yearly where a mainboard company files quarterly — so a
-- missing-filing alert that does not know the platform accuses the wrong companies.
ALTER TABLE securities ADD COLUMN platform text NOT NULL DEFAULT 'mainboard';
ALTER TABLE securities ADD CONSTRAINT securities_platform_check
    CHECK (platform IN ('mainboard', 'nse_emerge'));

-- ------------------------------------------------------------------------------------------------
-- Ingest bookkeeping
-- ------------------------------------------------------------------------------------------------

-- Every run of every fetcher, successful or not.
--
-- The rule this table exists to enforce: a feed that parses but returns zero items is a FAILURE,
-- not a success. v2's hardest-won operational lesson — a dead feed must never look like a quiet
-- day. Downstream jobs read this rather than the clock: the alert evaluator gates on a successful
-- run for today, because systemd timers are wall-clock and not a dependency graph.
CREATE TABLE ingestion_runs (
    id          bigserial   PRIMARY KEY,
    source      text        NOT NULL,
    started_at  timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    status      text        NOT NULL DEFAULT 'running',
    items       integer     NOT NULL DEFAULT 0,
    detail      text,

    CONSTRAINT ingestion_runs_status_check CHECK (status IN ('running', 'ok', 'failed'))
);

CREATE INDEX ingestion_runs_source_idx ON ingestion_runs (source, started_at DESC);

-- ------------------------------------------------------------------------------------------------
-- Prices
-- ------------------------------------------------------------------------------------------------

-- End of day only. There are no intraday quotes in v3: they existed in v2 for a Kite integration
-- whose access token had to be regenerated by a human every trading morning, silently gating four
-- jobs. The bhavcopy needs no token.
CREATE TABLE prices (
    symbol     text           NOT NULL,
    on_date    date           NOT NULL,
    open       numeric(18, 4),
    high       numeric(18, 4),
    low        numeric(18, 4),
    close      numeric(18, 4) NOT NULL,
    volume     bigint,
    source     text           NOT NULL DEFAULT 'nse_bhavcopy',

    PRIMARY KEY (symbol, on_date)
);

CREATE INDEX prices_date_idx ON prices (on_date DESC);

-- ------------------------------------------------------------------------------------------------
-- Filings
-- ------------------------------------------------------------------------------------------------

CREATE TABLE filings (
    id             text        PRIMARY KEY,
    company_id     text        REFERENCES companies (id),
    symbol         text        NOT NULL,
    category       text,
    subject        text,
    announced_at   timestamptz NOT NULL,
    attachment_url text,
    -- Set once the attachment has been fetched and stored. Null means not fetched; a row in
    -- attachments means fetched and readable.
    attachment_sha256 text     REFERENCES attachments (sha256),
    fetched_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX filings_company_idx ON filings (company_id, announced_at DESC);
CREATE INDEX filings_symbol_idx  ON filings (symbol, announced_at DESC);

-- ------------------------------------------------------------------------------------------------
-- Financial results
-- ------------------------------------------------------------------------------------------------

-- One row per company per period per basis. The XBRL parser (lib/ingest/xbrl.ts) produces these,
-- and the columns it cannot fill are left null rather than zeroed: zero is a real figure in a
-- financial statement and inventing one is worse than admitting the gap.
CREATE TABLE fundamentals (
    id            text        PRIMARY KEY,
    company_id    text        NOT NULL REFERENCES companies (id),
    basis         text        NOT NULL,
    period_start  date        NOT NULL,
    period_end    date        NOT NULL,
    period_kind   text        NOT NULL,
    audited       boolean,

    revenue           numeric(20, 2),
    other_income      numeric(20, 2),
    total_expenses    numeric(20, 2),
    profit_before_tax numeric(20, 2),
    profit_after_tax  numeric(20, 2),
    eps_basic         numeric(12, 4),
    eps_diluted       numeric(12, 4),

    -- The whole reason lib/ingest/xbrl.ts exists. NSE's year-to-date context declares the
    -- quarter's dates while carrying nine months of figures; measured 06-Sep-2026 across 24 live
    -- filings, all 24 disagreed. Recorded per row so a doubtful period can be found later.
    context_dates_disagreed boolean NOT NULL DEFAULT false,
    -- The period came from the context rather than from reported facts, which is the weaker source.
    period_inferred         boolean NOT NULL DEFAULT false,

    xbrl_url      text,
    xbrl_sha256   text,
    filed_at      timestamptz,
    -- A restatement is a new row, not an edit. The old figures are what was believed at the time.
    superseded_by text        REFERENCES fundamentals (id),
    created_at    timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fundamentals_basis_check CHECK (basis IN ('standalone', 'consolidated')),
    CONSTRAINT fundamentals_kind_check
        CHECK (period_kind IN ('quarter', 'half_year', 'year_to_date', 'year')),
    CONSTRAINT fundamentals_period_check CHECK (period_end > period_start)
);

CREATE UNIQUE INDEX fundamentals_period_idx
    ON fundamentals (company_id, basis, period_start, period_end)
    WHERE superseded_by IS NULL;

-- ------------------------------------------------------------------------------------------------
-- Insider dealing and shareholding
-- ------------------------------------------------------------------------------------------------

-- SEBI PIT disclosures. Promoter pledge and pledge invocation are the loudest signals a smallcap
-- gives, which is why this is ingested rather than read on a website when somebody remembers.
CREATE TABLE insider_transactions (
    id            text        PRIMARY KEY,
    company_id    text        REFERENCES companies (id),
    symbol        text        NOT NULL,
    person        text,
    category      text,
    kind          text,
    quantity      numeric(20, 2),
    value         numeric(20, 2),
    mode          text,
    disclosed_at  timestamptz NOT NULL,
    period_start  date,
    period_end    date,
    fetched_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX insider_company_idx ON insider_transactions (company_id, disclosed_at DESC);

CREATE TABLE shareholding_patterns (
    id                 text    PRIMARY KEY,
    company_id         text    NOT NULL REFERENCES companies (id),
    as_of              date    NOT NULL,
    promoter_pct       numeric(8, 4),
    promoter_pledge_pct numeric(8, 4),
    public_pct         numeric(8, 4),
    fii_pct            numeric(8, 4),
    dii_pct            numeric(8, 4),
    fetched_at         timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT shareholding_unique UNIQUE (company_id, as_of)
);

