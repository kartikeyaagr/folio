// Three rules here are load-bearing.
//
// 1. `lib/` is imported by BOTH the Next.js app and the standalone tsx jobs. A `next/*` import
//    inside lib/ compiles fine for the web app and dies at runtime in a job. v2 got this
//    guarantee for free because its services were Python and physically could not import
//    TypeScript; the one-package decision removes that, so a lint rule replaces it.
//
// 2. The backend must be provable without the frontend. app/ may import lib/; lib/, jobs/ and
//    db/ may never import app/. One-way, so the backend can be built, tested and run with no UI
//    in the tree, and stays that way once the UI lands.
//
// 3. The 300-line cap exists because v2's `lib/pipeline.ts` reached 2,007 lines. There was no
//    boundary between fetching and rendering, so one file absorbed both.
//
// 4. The casing convention was held by hand across 2,237 declarations with nothing enforcing it.
//    Audited 21-Sep-2026: 1,302 variables, 684 functions and 251 types, zero violations. A rule
//    that passes on the day it lands costs nothing and stops the drift, which is the same bargain
//    as the two import bans above.
//
// NOTE: `no-restricted-imports` is set once per matched path. Flat config is later-wins for the
// same rule name, so two blocks both matching `lib/**` silently drop the earlier one's patterns —
// which is exactly what happened on the first attempt, and the ban did not fire. Keep every
// pattern for a given path inside that path's single block. (The naming block below is safe under
// that rule: it is the only place `naming-convention` is set.)
import tseslint from 'typescript-eslint';

/** The backend never reaches for the UI. */
const noAppImports = {
  group: ['@/app', '@/app/**', '**/app/**'],
  message: 'The backend does not depend on the UI. app/ imports lib/, never the reverse.',
};

/** lib/ runs under raw tsx in the jobs, where there is no Next runtime. */
const noNextImports = {
  group: ['next', 'next/*', 'server-only'],
  message: 'lib/ is imported by the tsx jobs, which have no Next runtime. Keep Next imports in app/.',
};

export default tseslint.config(
  // next-env.d.ts is generated by Next on every build and is not ours to lint.
  { ignores: ['.next/**', 'node_modules/**', 'next-env.d.ts'] },
  ...tseslint.configs.recommended,
  {
    // Casing, enforced. The carve-outs are the point: two kinds of name in this tree are not ours
    // to choose, and renaming either breaks something rather than tidying it.
    //
    // `objectLiteralProperty` and `typeProperty` are exempt because they spell Postgres columns
    // (`created_at`, `profit_after_tax`) and vendor wire formats (Anthropic's `max_tokens`,
    // csv-parse's `relax_column_count`, NSE's `sm_isin`). `query<T>` is a cast and never a parse,
    // so a row key renamed here typechecks green and reads `undefined` at runtime. The agent
    // output keys are worse than that: `by_company` and `why_it_matters` are stored inside jsonb
    // correction paths, so renaming one is a data migration.
    //
    // The invariant the codebase actually holds, and this rule protects, is narrower and worth
    // stating: snake_case never crosses a module boundary. Every exported type is camelCase,
    // mapped either by an `AS "camelCase"` alias in the SQL or by an explicit `rows.map`.
    files: ['**/*.ts', '**/*.tsx'],
    rules: {
      '@typescript-eslint/naming-convention': [
        'error',
        { selector: ['objectLiteralProperty', 'typeProperty'], format: null },
        // A destructured name is the source's name, not a new one. Same argument as above.
        { selector: 'variable', modifiers: ['destructured'], format: null },
        // PascalCase for React components held in a const; UPPER_CASE for module constants, which
        // this tree reserves for immutable module scope and never uses inside a function body.
        { selector: 'variable', format: ['camelCase', 'UPPER_CASE', 'PascalCase'] },
        { selector: 'function', format: ['camelCase', 'PascalCase'] },
        // `_request` on a route handler that ignores it is the conventional signal, not a slip.
        { selector: 'parameter', format: ['camelCase'], leadingUnderscore: 'allow' },
        { selector: 'typeLike', format: ['PascalCase'] },
      ],
    },
  },
  {
    files: ['lib/**/*.ts'],
    rules: {
      'no-restricted-imports': ['error', { patterns: [noNextImports, noAppImports] }],
      'max-lines': ['warn', { max: 300, skipBlankLines: true, skipComments: true }],
    },
  },
  {
    files: ['jobs/**/*.ts', 'db/**/*.ts'],
    rules: {
      'no-restricted-imports': ['error', { patterns: [noAppImports] }],
    },
  },
);
